package com.ps.stashit.core.captions

import com.google.gson.annotations.SerializedName
import retrofit2.http.Body
import retrofit2.http.POST

interface CaptionApi {
    @POST("captions")
    suspend fun getCaptions(@Body request: CaptionRequest): CaptionResponse
}

data class CaptionRequest(
    val url: String,
    val languages: List<String> = listOf("en"),
    @SerializedName("allow_audio_fallback") val allowAudioFallback: Boolean = true
)

data class CaptionResponse(
    val platform: String?,
    @SerializedName("video_id") val videoId: String?,
    val source: String?,
    @SerializedName("duration_seconds") val durationSeconds: Double?,
    val language: String?,
    @SerializedName("is_auto_generated") val isAutoGenerated: Boolean?,
    @SerializedName("full_text") val fullText: String?,
    val segments: List<CaptionSegment>?
)

data class CaptionSegment(
    val text: String,
    val start: Double,
    val duration: Double
)
